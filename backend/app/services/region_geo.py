"""Country code → display name and an approximate label point for the map.

``services/egress_regions.py`` decides *which* country a destination belongs to
(that is a fact it can prove from a CIDR table). It deliberately carries no
labels, so a page that wants to say "美国" rather than "US" - or to put a marker
on a map - needs that second table, and it needs it to be the same one
everywhere. It lives here once for that reason.

Both tables are reference data, not measurements: the point is a country's
centroid to about a degree, which is all a marker on a wall display needs. A
code with no entry stays unlabeled and unplaced (``name`` falls back to the
code, ``point`` returns ``None``), and the page is expected to say so rather
than scatter the marker somewhere it does not belong.
"""
