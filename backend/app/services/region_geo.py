def country_name(code: str) -> str:
    """The display name for a region code; the code itself when unknown."""
    key = str(code or "").strip().upper()
    return COUNTRY_NAMES.get(key, key)


def country_point(code: str) -> tuple[float, float] | None:
    """The ``(lat, lon)`` label point, or ``None`` when there is no entry."""
    return COUNTRY_POINTS.get(str(code or "").strip().upper())


